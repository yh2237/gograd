TEXT ·hasAVX2FMA(SB), NOSPLIT, $0-1
	MOVL $1, AX
	CPUID
	MOVL CX, R8
	ANDL $(1<<12 | 1<<27 | 1<<28), R8
	CMPL R8, $(1<<12 | 1<<27 | 1<<28)
	JNE noavx
	XORL CX, CX
	XGETBV
	ANDL $6, AX
	CMPL AX, $6
	JNE noavx
	MOVL $7, AX
	XORL CX, CX
	CPUID
	TESTL $(1<<5), BX
	JZ noavx
	MOVB $1, ret+0(FP)
	RET
noavx:
	MOVB $0, ret+0(FP)
	RET

// 4x8 row-major tile with eight output columns in each YMM accumulator.
TEXT ·kernel4x8AVX(SB), NOSPLIT, $0-41
	MOVQ c+0(FP), CX
	MOVQ a+8(FP), AX
	MOVQ b+16(FP), BX
	MOVQ stride+24(FP), DX
	SHLQ $2, DX
	MOVQ k+32(FP), R8
	MOVBLZX add+40(FP), R9
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	TESTQ R9, R9
	JZ loopcheck8
	VMOVUPS (CX), Y0
	VMOVUPS (CX)(DX*1), Y1
	LEAQ (CX)(DX*2), R10
	VMOVUPS (R10), Y2
	ADDQ DX, R10
	VMOVUPS (R10), Y3
loopcheck8:
	TESTQ R8, R8
	JZ finish8
loop8:
	VMOVUPS (BX), Y4
	VBROADCASTSS (AX), Y5
	VFMADD231PS Y4, Y5, Y0
	VBROADCASTSS 4(AX), Y5
	VFMADD231PS Y4, Y5, Y1
	VBROADCASTSS 8(AX), Y5
	VFMADD231PS Y4, Y5, Y2
	VBROADCASTSS 12(AX), Y5
	VFMADD231PS Y4, Y5, Y3
	ADDQ $16, AX
	ADDQ $32, BX
	DECQ R8
	JNZ loop8
finish8:
	VMOVUPS Y0, (CX)
	VMOVUPS Y1, (CX)(DX*1)
	LEAQ (CX)(DX*2), R10
	VMOVUPS Y2, (R10)
	ADDQ DX, R10
	VMOVUPS Y3, (R10)
	VZEROUPPER
	RET

// kernel4x16AVX computes a 4x16 block of C += A*B. A holds four rows of k
// floats and B holds sixteen columns of k floats, both packed so one k-step
// reads 16 bytes of A and 64 bytes of B. Six loads feed eight FMAs, which is
// one load fewer per FMA than the 4x8 kernel.
TEXT ·kernel4x16AVX(SB), NOSPLIT, $0-41
	MOVQ c+0(FP), CX
	MOVQ a+8(FP), AX
	MOVQ b+16(FP), BX
	MOVQ stride+24(FP), DX
	SHLQ $2, DX
	MOVQ k+32(FP), R8
	MOVBLZX add+40(FP), R9
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	TESTQ R9, R9
	JZ check4x16
	MOVQ CX, R10
	VMOVUPS (R10), Y0
	VMOVUPS 32(R10), Y1
	ADDQ DX, R10
	VMOVUPS (R10), Y2
	VMOVUPS 32(R10), Y3
	ADDQ DX, R10
	VMOVUPS (R10), Y4
	VMOVUPS 32(R10), Y5
	ADDQ DX, R10
	VMOVUPS (R10), Y6
	VMOVUPS 32(R10), Y7
check4x16:
	TESTQ R8, R8
	JZ finish4x16
loop4x16:
	VMOVUPS (BX), Y8
	VMOVUPS 32(BX), Y9
	VBROADCASTSS (AX), Y10
	VFMADD231PS Y8, Y10, Y0
	VFMADD231PS Y9, Y10, Y1
	VBROADCASTSS 4(AX), Y10
	VFMADD231PS Y8, Y10, Y2
	VFMADD231PS Y9, Y10, Y3
	VBROADCASTSS 8(AX), Y10
	VFMADD231PS Y8, Y10, Y4
	VFMADD231PS Y9, Y10, Y5
	VBROADCASTSS 12(AX), Y10
	VFMADD231PS Y8, Y10, Y6
	VFMADD231PS Y9, Y10, Y7
	ADDQ $16, AX
	ADDQ $64, BX
	DECQ R8
	JNZ loop4x16
finish4x16:
	MOVQ CX, R10
	VMOVUPS Y0, (R10)
	VMOVUPS Y1, 32(R10)
	ADDQ DX, R10
	VMOVUPS Y2, (R10)
	VMOVUPS Y3, 32(R10)
	ADDQ DX, R10
	VMOVUPS Y4, (R10)
	VMOVUPS Y5, 32(R10)
	ADDQ DX, R10
	VMOVUPS Y6, (R10)
	VMOVUPS Y7, 32(R10)
	VZEROUPPER
	RET

